/** v2 `ImageModeDefSchema`, minus the v2-only transport/limit fields. */
export interface ImageModeDef {
  supports: Partial<Record<CanonicalParamKey, SupportSpec>>
  /** v2 `requirePrompt`: `false` skips the generic non-empty-prompt check. */
  requirePrompt?: boolean
}

/** v2 `ImageGenerationSupportSchema`. */
export interface ImageGenerationSupport {
  modes: Partial<Record<ImageGenerationMode, ImageModeDef>>
}

/** One ported (owner, modelId) support block with its v2 provenance. */
export interface ImageGenerationCatalogEntry {
  /** v2 provider id (override) or creator id (creator default). */
  owner: string
  modelId: string
  provenance: {
    /** Explicit per-(provider, model) override wins over the creator default. */
    source: 'provider' | 'creator'
    file: string
    line?: number
    /** Set when the v2 block is pipeline-generated (no hand-written override). */
    note?: string
  }
  support: ImageGenerationSupport
}

