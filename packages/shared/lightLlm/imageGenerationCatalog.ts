/**
 * Resolve the support block for a (provider, modelId) pair — the fork equivalent of
 * v2 `ProviderRegistryService.getImageGenerationSupport`, same resolution order:
 *
 *   1. the provider override (v2 `lookupModel` → `registryOverride.imageGeneration`)
 *   2. the creator default (v2 `presetModel.imageGeneration`)
 *   3. `null` — not on this plane; the caller must raise an explicit error.
 *
 * v2 override `apiModelId` aliases are indexed under BOTH spellings, because a fork
 * model id may carry either the catalog key or the vendor wire id.
 */
export function getImageGenerationSupport(
  providerId: string | undefined,
  modelId: string | undefined
): ImageGenerationSupport | null {
  const entry = getImageGenerationCatalogEntry(providerId, modelId)
  return entry ? entry.support : null
}

/** The catalog entry (support + provenance) for a pair, or `null`. */
export function getImageGenerationCatalogEntry(
  providerId: string | undefined,
  modelId: string | undefined
): ImageGenerationCatalogEntry | null {
  if (!providerId || !modelId) return null
  const providerTable = PROVIDER_SUPPORTS[providerId + '/' + modelId]
  if (providerTable) {
    return {
      owner: providerId,
      modelId,
      provenance: { source: 'provider', ...PROVIDER_PROVENANCE[providerId + '/' + modelId] },
      support: toSupport(providerId + '/' + modelId, providerTable)
    }
  }
  const creatorTable = CREATOR_SUPPORTS[providerId + '/' + modelId]
  if (creatorTable) {
    return {
      owner: providerId,
      modelId,
      provenance: { source: 'creator', ...CREATOR_PROVENANCE[providerId + '/' + modelId] },
      support: toSupport(providerId + '/' + modelId, creatorTable)
    }
  }
  const aliased = API_MODEL_ID_ALIASES[providerId + '/' + modelId]
  if (aliased !== undefined) return getImageGenerationCatalogEntry(providerId, aliased)
  return null
}

/** Every ported entry, for tests/inspection. */
export const IMAGE_GENERATION_CATALOG_ENTRIES: readonly ImageGenerationCatalogEntry[] = (
  [
    ...Object.keys(PROVIDER_SUPPORTS).map((key) => ({ key, source: 'provider' as const })),
    ...Object.keys(CREATOR_SUPPORTS).map((key) => ({ key, source: 'creator' as const }))
  ] as const
).map(({ key }) => {
  const slash = key.indexOf('/')
  const entry = getImageGenerationCatalogEntry(key.slice(0, slash), key.slice(slash + 1))
  if (!entry) throw new Error(`imageGenerationCatalog: unresolvable entry ${key}`)
  return entry
})

// ── Wire mapping (fork 缝) ──────────────────────────────────────────────────
//
// v2 splits this across three files: `imageParamCatalog.wireName` (the canonical →
// snake_case rename + the `wire` overrides), `AI_SDK_NATIVE_BINDINGS` (the four
// fields the AI SDK consumes as typed options) and `wireProfile.ts` (the per-provider
// `forward` / `fields` body map + `WIRE_REGISTRY`). The fork posts ONE flat JSON body
// to `/v1/images/generations`, so the three collapse here into: native binding →
// `option`, else profile `to`/`contribute`, else `wireName(key)`.
//
// Providers ABSENT from `IMAGE_WIRE_PROFILES` are off this plane: the main process
// refuses the request with an explicit `UNSUPPORTED_VENDOR` error rather than
// forwarding a body the vendor cannot read.

/** `camelCase` → `snake_case` (v2 `wireName` AUTO form). */
function autoSnakeCase(key: string): string {
  return key.replace(/[A-Z]/g, (m) => `_${m.toLowerCase()}`)
}

/** v2 `IMAGE_PARAM_CATALOG[key].wire` overrides — only the irregular spellings. */
const WIRE_NAME_OVERRIDES: Record<string, string> = {
  addWatermark: 'watermark',
  imageResolution: 'size'
}

/** The vendor wire field name for a canonical param (v2 `wireName`). */
export function wireName(key: string): string {
  return WIRE_NAME_OVERRIDES[key] ?? autoSnakeCase(key)
}

/**
 * v2 `normalizeAspectRatio`: the registry stores `ASPECT_16_9`, vendors read `16:9`.
 * Invalid / blank values return `undefined` so the field is omitted entirely.
 */
export function normalizeAspectRatio(value: unknown): string | undefined {
  if (typeof value !== 'string' || value === '') return undefined
  const stripped = value.replace(/^ASPECT_/i, '').replace('_', ':')
  return /^\d+(?:\.\d+)?:\d+(?:\.\d+)?$/.test(stripped) ? stripped : undefined
}

/**
 * v2 `AI_SDK_NATIVE_BINDINGS`: canonical key → the request field the vendor plane
 * consumes, with `aspectRatio` normalized once (v2 does this in `splitParamValues`).
 * `numImages → n` is the only rename.
 */
const NATIVE_BINDINGS: Partial<Record<CanonicalParamKey, { option: string; map?: (value: unknown) => unknown }>> = {
  numImages: { option: 'n' },
  size: { option: 'size' },
  seed: { option: 'seed' },
  aspectRatio: { option: 'aspect_ratio', map: normalizeAspectRatio }
}

/** One profile rule: a literal wire field, a value transform, or a nested block. */
type WireRule =
  | { to: string; map?: (value: unknown, all: Record<string, unknown>) => unknown }
  | { contribute: (value: unknown, all: Record<string, unknown>) => Record<string, unknown> }

/** Per-provider body map — v2 `WireProfile` (+ its `WIRE_REGISTRY` row). */
export interface ImageWireProfile {
  /** Plain fields: forwarded as `wireName(key) → value` (v2 `forward`). */
  readonly forward: readonly CanonicalParamKey[]
  /** Explicit overrides — irregular name / value transform / nested block. */
  readonly fields: Partial<Record<CanonicalParamKey, WireRule>>
  /** Body fields every request carries, `paramValues`-independent (v2 transport). */
  readonly extraBody?: Readonly<Record<string, unknown>>
}

