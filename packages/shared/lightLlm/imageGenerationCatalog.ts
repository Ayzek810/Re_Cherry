function toSupport(key: string, table: Record<string, Record<string, number>>): ImageGenerationSupport {
  const modes: ImageGenerationSupport['modes'] = {}
  const promptFlags = REQUIRE_PROMPT[key] ?? {}
  for (const mode of MODE_ORDER) {
    const indices = table[mode]
    if (!indices) continue
    const supports: Partial<Record<CanonicalParamKey, SupportSpec>> = {}
    for (const [supportKey, index] of Object.entries(indices)) {
      supports[supportKey as CanonicalParamKey] = SUPPORT_SPECS[index]
    }
    modes[mode] = { supports, ...(promptFlags[mode] !== undefined && { requirePrompt: promptFlags[mode] }) }
  }
  return { modes }
}

