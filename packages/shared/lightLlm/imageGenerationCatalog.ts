/**
 * Map a canonical `paramValues` bag to a flat vendor request body.
 *
 * Mirrors v2 `splitParamValues` + `buildImageRequest`:
 *  - blank / `null` / `""` / `"auto"` values are dropped (the byte-identical-wire
 *    invariant, v2 `skipValue`);
 *  - a native binding wins (`numImages → n`, `aspectRatio → aspect_ratio` normalized);
 *  - else the profile field rule (`to` / `contribute`);
 *  - else `wireName(key)` when the key is in the profile's `forward` list;
 *  - anything else is DROPPED, so a vendor is never sent a field its profile does
 *    not declare (v2 behaviour — a profile never got the whole bag).
 */
export function buildImageWireBody(
  profile: ImageWireProfile,
  paramValues: Record<string, unknown>
): Record<string, unknown> {
  const body: Record<string, unknown> = {}

  for (const [key, value] of Object.entries(paramValues)) {
    if (value === undefined || value === '' || value === null || value === 'auto') continue
    const binding = NATIVE_BINDINGS[key as CanonicalParamKey]
    if (binding) {
      const mapped = binding.map ? binding.map(value) : value
      if (mapped !== undefined && mapped !== null && mapped !== '' && mapped !== 'auto') {
        body[binding.option] = mapped
      }
      continue
    }
    const rule = profile.fields[key as CanonicalParamKey]
    if (rule) {
      if ('contribute' in rule) {
        Object.assign(body, rule.contribute(value, paramValues))
      } else {
        body[rule.to] = rule.map ? rule.map(value, paramValues) : value
      }
      continue
    }
    if ((profile.forward as readonly string[]).includes(key)) {
      body[wireName(key)] = value
    }
  }

  return { ...(profile.extraBody ?? {}), ...body }
}

// ── Param bag validation / coercion (fork 缝) ───────────────────────────────
//
// v2 composes a zod schema per (model, mode) in `buildParamsSchema`: the catalog owns
// each key's value type, the per-model `SupportSpec` layers enum/range constraints on
// top, every field is `.catch(undefined)` and the object is `.loose()` so one bad or
// legacy value never fails the whole submit. The fork has no zod on this wire path, so
// the same semantics are implemented directly below — identical observable behaviour:
// blanks → omitted, out-of-constraint → omitted, unknown keys → kept for the caller
// (the legacy-key compatibility path in `canonicalGenerate`).

/** v2 `blankToUndefined`: a blank text input reads as "omitted", never 0/NaN. */
function coerceKind(kind: CanonicalParamKind, value: unknown): unknown {
  if (value === '' || value === null || value === undefined) return undefined
  if (kind === 'string') return typeof value === 'string' ? value : String(value)
  if (kind === 'bool') return typeof value === 'boolean' ? value : undefined
  const numeric = typeof value === 'number' ? value : Number(value)
  if (!Number.isFinite(numeric)) return undefined
  return kind === 'int' ? Math.trunc(numeric) : numeric
}

/** v2 `resolveModeSupports`: the requested mode, else the model's first mode. */
function resolveModeSupports(
  support: ImageGenerationSupport | undefined,
  mode: ImageGenerationMode
): Partial<Record<CanonicalParamKey, SupportSpec>> | undefined {
  const modes = support?.modes
  if (!modes) return undefined
  const fallback = MODE_ORDER.find((candidate) => modes[candidate])
  return (modes[mode] ?? (fallback ? modes[fallback] : undefined))?.supports
}

/** v2 `applyConstraints`: enum options / range bounds, `custom` always allowed. */
function satisfiesConstraints(value: unknown, spec: SupportSpec): boolean {
  if (spec.type === 'enum') {
    return value == null || value === 'custom' || spec.options.includes(String(value))
  }
  if (spec.type === 'range') {
    const numeric = Number(value)
    return value == null || (Number.isFinite(numeric) && numeric >= spec.min && numeric <= spec.max)
  }
  return true
}

/**
 * Validate + coerce a raw form-params bag against a model's support block — the fork
 * equivalent of v2 `buildParamsSchema(support, mode).safeParse(params)`.
 *
 * Returns a bag containing every canonical key (omitted when blank / invalid) plus
 * untouched non-canonical keys, so a legacy or vendor-specific entry survives and the
 * caller decides what to do with it (v2 `.loose()` + `buildParamsSchema`'s `.catch`).
 */
export function buildParamsSchema(
  support: ImageGenerationSupport | undefined,
  mode: ImageGenerationMode = 'generate'
): (params: Record<string, unknown>) => Record<string, unknown> {
  const supports = resolveModeSupports(support, mode)
  return (params) => {
    const out: Record<string, unknown> = {}
    for (const [key, raw] of Object.entries(params)) {
      const canonical = (CANONICAL_PARAM_KEYS as readonly string[]).includes(key)
      if (!canonical) {
        out[key] = raw
        continue
      }
      const coerced = coerceKind(CANONICAL_PARAM_KINDS[key as CanonicalParamKey], raw)
      if (coerced === undefined) continue
      const spec = supports?.[key as CanonicalParamKey]
      if (spec && !satisfiesConstraints(coerced, spec)) continue
      out[key] = coerced
    }
    return out
  }
}
